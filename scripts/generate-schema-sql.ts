/**
 * Regenerates schema.sql from packages/db/migrations, so the one-file view of the schema can't
 * drift from what the migrations build. The integration suite compares the two.
 *
 * It creates a scratch database, runs the migrations into it, dumps the schema with pg_dump and
 * drops the database again. The server needs CREATEDB rights, and pg_dump must be the server's
 * major version or newer. Build packages/db first, because the migrations run from its dist.
 *
 * Usage:
 *   SCHEMA_ADMIN_URL=postgres://postgres@127.0.0.1:55532/postgres \
 *     PG_DUMP=/opt/homebrew/opt/postgresql@17/bin/pg_dump npm run db:schema
 */

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import pg from 'pg';
import { resetConfig } from '@immoradar/config';
import { closePool, runMigrations } from '@immoradar/db';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SCHEMA_PATH = join(ROOT, 'schema.sql');

const HEADER = `-- schema.sql
-- The whole schema in one file, for reading. Generated by \`npm run db:schema\` from
-- packages/db/migrations: don't edit it by hand. Add a migration, then regenerate.
-- Real databases are built by the migrations only. This file loads into an empty database.
`;

// pg_dump's banners carry versions and object names that only add noise to diffs.
const BANNER = /^--( Name: | Data for Name: | PostgreSQL database dump| Dumped (from|by) |$)/;

function tidyDump(dump: string): string {
  const lines = dump.split('\n').filter((line) => {
    if (BANNER.test(line)) return false;
    // Session settings, and the \restrict guard that newer pg_dump releases add for psql.
    if (line.startsWith('SET ') || line.startsWith('SELECT pg_catalog.set_config(')) return false;
    if (line.startsWith('\\restrict ') || line.startsWith('\\unrestrict ')) return false;
    return true;
  });

  // Only statement heads are rewritten. Function bodies keep their text exactly, because the
  // drift check compares them.
  const body = lines
    .join('\n')
    .replace(/^CREATE TABLE public\./gm, 'CREATE TABLE IF NOT EXISTS ')
    .replace(/^CREATE (UNIQUE )?INDEX /gm, 'CREATE $1INDEX IF NOT EXISTS ')
    .replace(/^CREATE FUNCTION public\./gm, 'CREATE OR REPLACE FUNCTION ')
    .replace(/^CREATE TRIGGER /gm, 'CREATE OR REPLACE TRIGGER ')
    .replace(/^CREATE SEQUENCE public\./gm, 'CREATE SEQUENCE IF NOT EXISTS ')
    .replace(/^CREATE VIEW public\./gm, 'CREATE OR REPLACE VIEW ')
    .replace(/\n{3,}/g, '\n\n')
    .trim();

  return `${HEADER}\n${body}\n`;
}

async function main(): Promise<void> {
  const adminUrl = process.env['SCHEMA_ADMIN_URL'];
  if (!adminUrl) {
    throw new Error('Set SCHEMA_ADMIN_URL to a Postgres URL with CREATEDB rights.');
  }

  const dbName = `immoradar_schema_${process.pid}`;
  const target = new URL(adminUrl);
  target.pathname = `/${dbName}`;

  const admin = new pg.Client({ connectionString: adminUrl });
  await admin.connect();
  try {
    await admin.query(`DROP DATABASE IF EXISTS "${dbName}"`);
    await admin.query(`CREATE DATABASE "${dbName}"`);

    // Overrides any DATABASE_URL from the shell or .env, so the migrations can only reach the
    // scratch database.
    process.env['DATABASE_URL'] = target.toString();
    resetConfig();
    try {
      await runMigrations();
    } finally {
      await closePool();
    }

    const dump = execFileSync(
      process.env['PG_DUMP'] ?? 'pg_dump',
      [
        '--schema-only',
        '--no-owner',
        '--no-privileges',
        '--no-comments',
        // The runner's bookkeeping table and its sequence.
        '--exclude-table=_migrations*',
        `--dbname=${target.toString()}`,
      ],
      { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
    );
    writeFileSync(SCHEMA_PATH, tidyDump(dump));
    console.log(`Wrote ${SCHEMA_PATH}`);
  } finally {
    await admin.query(`DROP DATABASE IF EXISTS "${dbName}"`);
    await admin.end();
  }
}

main().catch((err: unknown) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
